class TestDockerfileRuntimeLockWiring:
    @pytest.fixture(scope="class")
    def dockerfile(self) -> str:
        return DOCKERFILE.read_text(encoding="utf-8")

    def test_build_stage_exports_frozen_closure_from_lock(self, dockerfile: str) -> None:
        assert "RUN uv export --frozen --no-dev --no-emit-project --no-hashes" in dockerfile
        assert "/build/wheel/requirements-runtime-frozen.txt" in dockerfile

    def test_runtime_sync_targets_the_explicit_venv(self, dockerfile: str) -> None:
        # --active syncs the environment named by VIRTUAL_ENV; a plain
        # `uv sync` would create and fill the project .venv instead (the
        # demonstrated defect).
        assert (
            "VIRTUAL_ENV=/opt/slaif/venv uv sync --frozen --no-dev --no-install-project --active"
            in dockerfile
        )

    def test_closure_file_copied_into_runtime_image(self, dockerfile: str) -> None:
        assert (
            "COPY --from=build /build/wheel/requirements-runtime-frozen.txt /opt/slaif/artifacts/"
            in dockerfile
        )

    def test_wheel_install_has_no_second_resolution(self, dockerfile: str) -> None:
        assert "uv pip install --python /opt/slaif/venv/bin/python --no-deps" in dockerfile

    def test_base_pins_unchanged(self, dockerfile: str) -> None:
        # Order: preserve base digests, build pins, and the stage set.
        python_base = (
            "FROM python:3.12-slim-bookworm@sha256:782412e85d0f0984994c290652577d4018"
            "aff08145c85b262bb63dc0c7522254"
        )
        uv_base = (
            "FROM ghcr.io/astral-sh/uv:0.12.5@sha256:e85be844203885286c60ffad8a858d4"
            "8afb6c5a5c237ca0e67f12e74b8f174b1"
        )
        assert python_base in dockerfile
        assert uv_base in dockerfile
        for stage in ("AS uv-provider", "AS build", "AS runtime"):
            assert stage in dockerfile
