"""Order 013-m, M1: focused tests for the frozen runtime lock closure gate.

The Dockerfile runtime stage must install the ACTUAL frozen lock closure
into /opt/slaif/venv (no second dependency resolution) and the in-image
provenance gate must compare the actually installed distributions against
the build-stage export of the committed uv.lock. Missing, wrong-version,
or unexpected runtime dependencies must FAIL the gate; the in-image audit
script must embed the exact tested function sources; the Dockerfile must
carry the explicit frozen-sync target and the --no-deps wheel install.

No Docker, no network: pure functions, generated audit code, and the
committed Dockerfile bytes only.
"""

