class TestInImageAuditCode:
    def test_compiles(self, dqc: types.ModuleType) -> None:
        code = dqc._runtime_venv_audit_code()
        compile(code, "<in-image-audit>", "exec")

    def test_embeds_exact_tested_function_sources(self, dqc: types.ModuleType) -> None:
        code = dqc._runtime_venv_audit_code()
        for fn in (
            dqc._slaif_canonical_name,
            dqc._slaif_parse_frozen_pins,
            dqc._slaif_marker_applies,
            dqc._slaif_evaluate_runtime_closure,
        ):
            assert inspect.getsource(fn) in code, f"source of {fn.__name__} not embedded"

    def test_driver_contract(self, dqc: types.ModuleType) -> None:
        code = dqc._runtime_venv_audit_code()
        # Existing checks preserved.
        assert 'md.distribution("slaif-local-coding")' in code
        assert 'assert dist.version == "0.1.0", dist.version' in code
        assert '"/site-packages/slaif_local_coding/" in loc' in code
        assert "hashlib.sha256(open(wheel, " in code
        # M1 closure inspection of the actually installed distributions.
        assert dqc.FROZEN_RUNTIME_CLOSURE_PATH in code
        assert "_slaif_parse_frozen_pins(pins_text)" in code
        assert "_slaif_evaluate_runtime_closure(pins, installed, " in code
        assert "md.distributions()" in code
        assert "raise SystemExit(1)" in code
        # Bounded JSON out, no secrets, no raw payloads.
        assert "json.dumps" in code


