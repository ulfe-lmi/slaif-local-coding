class TestEvaluateRuntimeClosure:
    PINS: dict[str, tuple[str, str | None]] = {
        "anyio": ("4.14.2", None),
        "pydantic": ("2.13.4", None),
        "colorama": ("0.4.6", "sys_platform == 'win32'"),
    }

    def _installed(self, **overrides: str) -> dict[str, str]:
        base = {
            "anyio": "4.14.2",
            "pydantic": "2.13.4",
            "slaif-local-coding": "0.1.0",
        }
        base.update(overrides)
        return base

    def test_exact_closure_passes(self, dqc: types.ModuleType) -> None:
        result = dqc._slaif_evaluate_runtime_closure(
            self.PINS, self._installed(), "slaif-local-coding", "0.1.0"
        )
        assert result["ok"] is True
        assert result["missing"] == {}
        assert result["wrong_version"] == {}
        assert result["unexpected"] == {}
        assert result["product_ok"] is True
        assert result["pinned_count"] == 3
        assert result["applicable_count"] == 2  # colorama not applicable here
        assert result["installed_count"] == 3
        assert result["installed"] == self._installed()

    def test_missing_dependency_fails(self, dqc: types.ModuleType) -> None:
        installed = self._installed()
        del installed["pydantic"]
        result = dqc._slaif_evaluate_runtime_closure(
            self.PINS, installed, "slaif-local-coding", "0.1.0"
        )
        assert result["ok"] is False
        assert result["missing"] == {"pydantic": "2.13.4"}

    def test_wrong_version_fails(self, dqc: types.ModuleType) -> None:
        # The exact drift the defect produced: the wheel install re-resolved
        # anyio to a newer version than the frozen lock.
        result = dqc._slaif_evaluate_runtime_closure(
            self.PINS, self._installed(**{"anyio": "4.15.1"}), "slaif-local-coding", "0.1.0"
        )
        assert result["ok"] is False
        assert result["wrong_version"] == {"anyio": {"installed": "4.15.1", "expected": "4.14.2"}}

    def test_unexpected_distribution_fails(self, dqc: types.ModuleType) -> None:
        result = dqc._slaif_evaluate_runtime_closure(
            self.PINS,
            self._installed(**{"requests": "2.32.0"}),
            "slaif-local-coding",
            "0.1.0",
        )
        assert result["ok"] is False
        assert result["unexpected"] == {"requests": "2.32.0"}

    def test_inapplicable_marker_dependency_installed_fails(self, dqc: types.ModuleType) -> None:
        # colorama is locked only for win32; on the supported platform it
        # must be ABSENT — a present colorama means the environment was
        # built by a different (second) resolution.
        result = dqc._slaif_evaluate_runtime_closure(
            self.PINS,
            self._installed(**{"colorama": "0.4.6"}),
            "slaif-local-coding",
            "0.1.0",
        )
        assert result["ok"] is False
        assert result["unexpected"] == {"colorama": "0.4.6"}

    def test_inapplicable_marker_dependency_absent_passes(self, dqc: types.ModuleType) -> None:
        result = dqc._slaif_evaluate_runtime_closure(
            self.PINS, self._installed(), "slaif-local-coding", "0.1.0"
        )
        assert result["ok"] is True

    def test_product_wheel_missing_fails(self, dqc: types.ModuleType) -> None:
        installed = self._installed()
        del installed["slaif-local-coding"]
        result = dqc._slaif_evaluate_runtime_closure(
            self.PINS, installed, "slaif-local-coding", "0.1.0"
        )
        assert result["ok"] is False
        assert result["product_ok"] is False

    def test_product_wheel_wrong_version_fails(self, dqc: types.ModuleType) -> None:
        result = dqc._slaif_evaluate_runtime_closure(
            self.PINS,
            self._installed(**{"slaif-local-coding": "9.9.9"}),
            "slaif-local-coding",
            "0.1.0",
        )
        assert result["ok"] is False
        assert result["product_ok"] is False

    def test_unsupported_marker_fails_closed(self, dqc: types.ModuleType) -> None:
        pins = {"anyio": ("4.14.2", "extra == 'x'")}
        with pytest.raises(ValueError):
            dqc._slaif_evaluate_runtime_closure(
                pins, self._installed(), "slaif-local-coding", "0.1.0"
            )


