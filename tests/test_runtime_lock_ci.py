class TestMarkerApplies:
    env = LINUX_AMD64_PY312_ENV

    def test_win32_marker_false_on_supported_platform(self, dqc: types.ModuleType) -> None:
        assert dqc._slaif_marker_applies("sys_platform == 'win32'", self.env) is False

    def test_linux_marker_true_on_supported_platform(self, dqc: types.ModuleType) -> None:
        assert dqc._slaif_marker_applies("sys_platform == 'linux'", self.env) is True

    def test_version_comparisons(self, dqc: types.ModuleType) -> None:
        assert dqc._slaif_marker_applies("python_version == '3.12'", self.env) is True
        assert dqc._slaif_marker_applies("python_version >= '3.11'", self.env) is True
        assert dqc._slaif_marker_applies("python_version >= '3.13'", self.env) is False
        assert dqc._slaif_marker_applies("python_version < '3.13'", self.env) is True
        # PEP 508 also allows unquoted version literals.
        assert dqc._slaif_marker_applies("python_version == 3.12", self.env) is True
        assert dqc._slaif_marker_applies("python_version >= 3.11", self.env) is True

    def test_version_tuple_zero_padding(self, dqc: types.ModuleType) -> None:
        # (3,12,14) vs (3,12): equal only after zero-padding the shorter
        # release for ORDERING, never for == (3.12.14 != 3.12).
        assert dqc._slaif_marker_applies("python_full_version == '3.12.14'", self.env) is True
        assert dqc._slaif_marker_applies("python_full_version == '3.12'", self.env) is False
        assert dqc._slaif_marker_applies("python_full_version >= '3.12'", self.env) is True
        assert dqc._slaif_marker_applies("python_full_version >= '3.12.15'", self.env) is False

    def test_and_joined_clauses(self, dqc: types.ModuleType) -> None:
        ok = dqc._slaif_marker_applies(
            "sys_platform == 'linux' and python_version >= '3.12'", self.env
        )
        assert ok is True
        bad = dqc._slaif_marker_applies(
            "sys_platform == 'linux' and python_version >= '3.13'", self.env
        )
        assert bad is False

    def test_real_interpreter_env_matches_sys_platform(self, dqc: types.ModuleType) -> None:
        # env=None builds the facts from the RUNNING interpreter (the
        # in-image call path); the result must equal the direct comparison.
        assert dqc._slaif_marker_applies("sys_platform == 'win32'") is (sys.platform == "win32")

    @pytest.mark.parametrize(
        "marker",
        [
            "sys_platform in 'linux'",  # in-operator: outside the closed grammar
            "not sys_platform == 'linux'",  # negation: outside the closed grammar
            "extra == 'x'",  # unknown variable
            "sys_platform == 'linux' or python_version == '3.12'",  # or: outside the grammar
        ],
    )
    def test_outside_closed_grammar_fails_closed(self, dqc: types.ModuleType, marker: str) -> None:
        with pytest.raises(ValueError):
            dqc._slaif_marker_applies(marker, self.env)


