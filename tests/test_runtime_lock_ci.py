class TestParseFrozenPins:
    def test_plain_pins_and_marker(self, dqc: types.ModuleType) -> None:
        text = (
            "# This file was autogenerated by uv via the following command:\n"
            "anyio==4.14.2\n"
            "certifi==2026.7.22\n"
            "colorama==0.4.6 ; sys_platform == 'win32'\n"
            "\n"
        )
        pins = dqc._slaif_parse_frozen_pins(text)
        assert pins == {
            "anyio": ("4.14.2", None),
            "certifi": ("2026.7.22", None),
            "colorama": ("0.4.6", "sys_platform == 'win32'"),
        }

    def test_comments_and_blanks_skipped(self, dqc: types.ModuleType) -> None:
        pins = dqc._slaif_parse_frozen_pins("# only a comment\n\nfastapi==0.141.1\n")
        assert pins == {"fastapi": ("0.141.1", None)}

    @pytest.mark.parametrize(
        "line",
        [
            "anyio",  # no version
            "anyio==",  # empty version
            "==4.14.2",  # no name
            "anyio==4.14.2 ; ",  # empty marker
            "anyio @ https://example.com/anyio.whl",  # URL form
            "anyio[extra]==4.14.2",  # extras are not in a lock export
            "--no-index",  # option lines
            "-r requirements.txt",  # option lines
        ],
    )
    def test_malformed_lines_rejected(self, dqc: types.ModuleType, line: str) -> None:
        with pytest.raises(ValueError):
            dqc._slaif_parse_frozen_pins(line + "\n")

    def test_duplicate_name_rejected(self, dqc: types.ModuleType) -> None:
        with pytest.raises(ValueError):
            dqc._slaif_parse_frozen_pins("anyio==4.14.2\nanyio==4.15.1\n")

    def test_empty_file_rejected(self, dqc: types.ModuleType) -> None:
        with pytest.raises(ValueError):
            dqc._slaif_parse_frozen_pins("")
        with pytest.raises(ValueError):
            dqc._slaif_parse_frozen_pins("# only comments\n\n")


